"""Build the two published forms of the roadmap from qa-comeback-plan.html.

    index.html                     the GitHub Pages site (loads lessons/ next to it)
    QA-Comeback-Plan-offline.html  one self-contained file: every lesson and the SQL
                                   engine inside, works with no internet

Run after any change to the page or the lessons:
    python build.py
"""
import json
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "qa-comeback-plan.html"
LESSONS = ROOT / "lessons"
SQLJS = ROOT / "vendor" / "sql-asm.js"
SITE = ROOT / "index.html"
OFFLINE = ROOT / "QA-Comeback-Plan-offline.html"
SPLIT = '<div class="wrap">'
MAIN_SCRIPT = "<script>\nconst START"


def wrap(head, body, note):
    return (
        "<!doctype html>\n<html lang=\"en\">\n<head>\n"
        "<meta charset=\"utf-8\">\n"
        "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1, viewport-fit=cover\">\n"
        f"<!-- {note}. Generated by build.py from qa-comeback-plan.html; edit that file, not this one. -->\n"
        "<style>body{margin:0} [hidden]{display:none!important} img{max-width:100%}</style>\n"
        f"{head}\n</head>\n<body>\n{body}\n</body>\n</html>\n"
    )


def main():
    page = SOURCE.read_text(encoding="utf-8")
    head, body = page.split(SPLIT, 1)
    body = SPLIT + body
    if MAIN_SCRIPT not in body:
        raise SystemExit("could not find the main script in the page")

    SITE.write_text(wrap(head, body, "GitHub Pages site"), encoding="utf-8")

    lessons = {
        f"lessons/{p.name}": p.read_text(encoding="utf-8")
        for p in sorted(LESSONS.glob("w*.html"))
    }
    lessons_js = json.dumps(lessons, ensure_ascii=False).replace("</", "<\\/")
    sqljs = SQLJS.read_text(encoding="utf-8")
    if "</script" in sqljs.lower():
        raise SystemExit("sql-asm.js contains </script>; cannot inline safely")
    inject = (
        f"<script>\n{sqljs}\n</script>\n"
        f"<script>window.OFFLINE_LESSONS = {lessons_js};</script>\n"
    )
    offline_body = body.replace(MAIN_SCRIPT, inject + MAIN_SCRIPT, 1)
    OFFLINE.write_text(wrap(head, offline_body, f"Offline copy built {date.today().isoformat()}"), encoding="utf-8")

    print(f"Wrote {SITE.name} and {OFFLINE.name} "
          f"({len(lessons)} lesson files, offline {OFFLINE.stat().st_size / 1_048_576:.1f} MB)")


if __name__ == "__main__":
    main()
